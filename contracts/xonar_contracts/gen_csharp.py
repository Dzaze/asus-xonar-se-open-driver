"""Génération des DTO C# des contrats.

Syntaxe volontairement limitée à C# 5 (constructeurs, propriétés automatiques,
pas d'initialiseurs de propriété) : le fichier se compile avec le csc du .NET
Framework présent sur Windows, ce qui permet de le vérifier sans SDK .NET, et
reste valide pour l'application WinUI 3 (fichier <auto-generated>, contexte
nullable désactivé). Les noms de propriétés sont le PascalCase exact des noms
JSON : JsonNamingPolicy.CamelCase les restitue à l'identique (vérifié ici).
Les valeurs filaires des énumérations passent par la classe Wire générée.
"""

from __future__ import annotations

from typing import Any

from .model import Manifest, Spec

CS_INT = {"u8": "byte", "u16": "ushort", "u32": "uint", "u64": "ulong", "i32": "int"}
CS_VALUE_TYPES = {"bool", "f64", *CS_INT}
CS_KEYWORDS = {"base", "class", "default", "enum", "event", "fixed", "int", "lock", "object", "operator",
               "out", "params", "ref", "string", "struct", "this", "checked", "decimal", "delegate"}
HEADER = """// <auto-generated>
// Généré par contracts/generate.py depuis contracts/manifest.json.
// Empreinte du manifeste (sha256, fins de ligne LF) : {sha}
// NE PAS MODIFIER À LA MAIN. Toute évolution passe par le manifeste ; un
// changement de version majeure exige un ADR, une migration et des tests.
// </auto-generated>
"""


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def camel_roundtrip(name: str) -> str:
    """Réplique JsonCamelCaseNamingPolicy (System.Text.Json) appliquée au PascalCase."""
    chars = list(pascal(name))
    if not chars or not chars[0].isupper():
        return "".join(chars)
    for i in range(len(chars)):
        if i == 1 and not chars[i].isupper():
            break
        has_next = i + 1 < len(chars)
        if i > 0 and has_next and not chars[i + 1].isupper():
            if chars[i + 1] == " ":
                chars[i] = chars[i].lower()
            break
        chars[i] = chars[i].lower()
    return "".join(chars)


def cs_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            raise ValueError(f"caractère non ASCII dans une constante : {s!r}")
    return '"' + "".join(out) + '"'


def cs_double(v: Any) -> str:
    r = repr(float(v))
    return r if ("." in r or "e" in r) else r + ".0"


def xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class CsGen:
    def __init__(self, m: Manifest):
        self.m = m
        self.lines: list[str] = []
        self.bases = self._bases()

    def w(self, line: str = "") -> None:
        self.lines.append(line)

    def doc(self, text: str, indent: str) -> None:
        if text:
            self.w(f"{indent}/// <summary>{xml(text)}</summary>")

    def _bases(self) -> dict[str, str]:
        bases: dict[str, str] = {}

        def put(t: str, b: str) -> None:
            if bases.get(t, b) != b:
                raise ValueError(f"{t} : deux classes de base ({bases[t]}, {b})")
            bases[t] = b

        for u in self.m.unions.values():
            for mem in u.members:
                put(mem, u.id)
        for st in self.m.structs.values():
            for f in st.fields:
                if f.spec.kind == "switch":
                    for case in f.spec.cases.values():
                        put(case.ref, f.spec.switch_base)
        return bases

    def ctype(self, spec: Spec) -> str:
        k = spec.kind
        if k == "bool":
            return "bool"
        if k == "f64":
            return "double"
        if k in CS_INT:
            return CS_INT[k]
        if k == "string":
            return "string"
        if k == "json":
            return "object"  # JsonElement avec System.Text.Json
        if k in ("enum", "struct", "union"):
            return spec.ref
        if k == "switch":
            return spec.switch_base
        if k == "array":
            inner = self.ctype(spec.item)
            return f"{inner}[]" if "length" in spec.array else f"List<{inner}>"
        raise ValueError(k)

    def literal(self, spec: Spec, v: Any) -> str:
        k = spec.kind
        if k == "bool":
            return "true" if v else "false"
        if k == "f64":
            return cs_double(v)
        if k == "u64":
            return f"{v}UL"
        if k == "u32":
            return f"{v}U"
        if k in CS_INT:
            return str(v)
        if k == "enum":
            return f"{spec.ref}.{self.m.enums[spec.ref].by_wire(v).id}"
        if k == "string":
            return cs_str(v)
        raise ValueError(k)

    def default_expr(self, spec: Spec, v: Any) -> str:
        if spec.kind == "struct":
            return f"new {spec.ref}()"
        if spec.kind == "array":
            if v == "$itemDefaults":
                return self._array_new(spec)
            return f"new {self.ctype(spec.item)}[] {{ {', '.join(self.literal(spec.item, x) for x in v)} }}"
        return self.literal(spec, v)

    def _array_new(self, spec: Spec) -> str:
        if spec.item.kind == "array":
            return f"Defaults.Jagged{self._jagged_name(spec)}()"
        return f"Defaults.Filled{spec.item.ref}({spec.array['length']})"

    def _jagged_name(self, spec: Spec) -> str:
        return f"{spec.item.item.ref}{spec.array['length']}x{spec.item.array['length']}"

    # ------------------------------------------------------------- sections
    def gen(self) -> str:
        m = self.m
        self.lines = HEADER.format(sha=m.sha256).splitlines()
        self.w("namespace Xonar.Contracts.V1")
        self.w("{")
        self.w("    using System;")
        self.w("    using System.Collections.Generic;")
        self.w("    using System.Collections.ObjectModel;")
        self.w()
        self.contracts()
        for e in m.enums.values():
            if e.emit:
                self.enum(e)
        self.wire()
        self.attrs()
        self.constants()
        self.limits()
        self.defaults_helpers()
        for name in m.type_order():
            if name in m.unions:
                self.union(name)
            else:
                self.struct(name)
        for st in m.structs.values():
            for f in st.fields:
                if f.spec.kind == "switch":
                    self.switch_base(f)
        self.w("}")
        return "\n".join(self.lines) + "\n"

    def contracts(self) -> None:
        self.w("    /// <summary>Versions des contrats C1…C8 et empreinte du manifeste.</summary>")
        self.w("    public static class ContractVersions")
        self.w("    {")
        self.w(f'        public const string ManifestSha256 = "{self.m.sha256}";')
        for c in self.m.contracts:
            self.w(f"        /// <summary>{xml(c['title'])}</summary>")
            self.w(f"        public const ushort {c['id']}Major = {c['major']};")
            self.w(f"        public const ushort {c['id']}Minor = {c['minor']};")
        self.w("    }")
        self.w()
        self.w("    /// <summary>Clé de propriété (FMTID + PID).</summary>")
        self.w("    public struct PropertyKey")
        self.w("    {")
        self.w("        public PropertyKey(Guid formatId, uint propertyId)")
        self.w("        {")
        self.w("            this.FormatId = formatId;")
        self.w("            this.PropertyId = propertyId;")
        self.w("        }")
        self.w()
        self.w("        public readonly Guid FormatId;")
        self.w("        public readonly uint PropertyId;")
        self.w("    }")
        self.w()
        self.w("    /// <summary>GUID attribués une seule fois par E0-02.</summary>")
        self.w("    public static class Guids")
        self.w("    {")
        for g in self.m.guids.values():
            self.doc(f"{g['doc']} [{g['contract']}]", "        ")
            self.w(f'        public static readonly Guid {g["id"]} = new Guid("{g["value"]}");')
            self.w(f'        public const string {g["id"]}String = "{{{g["value"]}}}";')
        for pk in self.m.property_keys:
            self.doc(f"{pk['doc']} [{pk['contract']}]", "        ")
            self.w(f"        public static readonly PropertyKey {pk['id']} = new PropertyKey({pk['fmtid']}, {pk['pid']}U);")
        self.w("    }")
        self.w()

    def enum(self, e) -> None:
        self.doc(f"{e.doc} [{e.contract}]", "    ")
        self.w(f"    public enum {e.id} : byte")
        self.w("    {")
        for v in e.values:
            self.doc(f"Valeur filaire « {v.wire} ». {v.doc}".strip(), "        ")
            self.w(f"        {v.id} = {v.index},")
        self.w("    }")
        self.w()

    def wire(self) -> None:
        self.w("    /// <summary>Noms filaires JSON des énumérations ; seule table de correspondance autorisée.</summary>")
        self.w("    public static class Wire")
        self.w("    {")
        for e in self.m.enums.values():
            if not e.emit:
                continue
            self.w(f"        public static string ToWire({e.id} value)")
            self.w("        {")
            self.w("            switch (value)")
            self.w("            {")
            for v in e.values:
                self.w(f'                case {e.id}.{v.id}: return "{v.wire}";')
            self.w('                default: throw new ArgumentOutOfRangeException("value");')
            self.w("            }")
            self.w("        }")
            self.w()
            self.w(f"        public static bool TryFromWire(string text, out {e.id} value)")
            self.w("        {")
            self.w("            switch (text)")
            self.w("            {")
            for v in e.values:
                self.w(f'                case "{v.wire}": value = {e.id}.{v.id}; return true;')
            self.w(f"                default: value = default({e.id}); return false;")
            self.w("            }")
            self.w("        }")
            self.w()
            vals = ", ".join(f"{e.id}.{v.id}" for v in e.values)
            self.w(f"        public static readonly ReadOnlyCollection<{e.id}> All{e.id} =")
            self.w(f"            new ReadOnlyCollection<{e.id}>(new {e.id}[] {{ {vals} }});")
            self.w()
        self.w("    }")
        self.w()

    def attrs(self) -> None:
        self.w("    /// <summary>Attributs des valeurs d'énumération (manifeste).</summary>")
        self.w("    public static class EnumAttributes")
        self.w("    {")
        for e in self.m.enums.values():
            if not e.emit:
                continue
            for an, at in e.attrs.items():
                spec = Spec("enum", ref=at[5:]) if at.startswith("enum:") else Spec(at)
                self.w(f"        public static {self.ctype(spec)} {pascal(an)}Of({e.id} value)")
                self.w("        {")
                self.w("            switch (value)")
                self.w("            {")
                for v in e.values:
                    self.w(f"                case {e.id}.{v.id}: return {self.literal(spec, v.attrs[an])};")
                self.w('                default: throw new ArgumentOutOfRangeException("value");')
                self.w("            }")
                self.w("        }")
                self.w()
        self.w("    }")
        self.w()

    def constants(self) -> None:
        self.w("    /// <summary>Constantes des contrats.</summary>")
        self.w("    public static class Constants")
        self.w("    {")
        for c in self.m.constants.values():
            self.doc(f"{c.doc} [{c.contract}]", "        ")
            t = c.type
            if isinstance(t, dict):
                item = t["array"]
                spec = Spec("enum", ref=item[5:]) if item.startswith("enum:") else Spec(item)
                ct = self.ctype(spec)
                vals = ", ".join(self.literal(spec, v) for v in c.value)
                self.w(f"        public static readonly ReadOnlyCollection<{ct}> {c.id} =")
                self.w(f"            new ReadOnlyCollection<{ct}>(new {ct}[] {{ {vals} }});")
            else:
                spec = Spec(t)
                self.w(f"        public const {self.ctype(spec)} {c.id} = {self.literal(spec, c.value)};")
        self.w("    }")
        self.w()

    def limits(self) -> None:
        for name in self.m.type_order():
            if name not in self.m.structs:
                continue
            rows: list[str] = []
            for f in self.m.structs[name].fields:
                spec = f.spec
                if spec.kind == "array":
                    if "length" in spec.array:
                        rows.append(f"        public const int {pascal(f.name)}Length = {spec.array['length']};")
                    if "maxItems" in spec.array:
                        rows.append(f"        public const int {pascal(f.name)}MaxItems = {spec.array['maxItems']};")
                    while spec.kind == "array":
                        spec = spec.item
                if spec.kind not in ("f64", *CS_INT, "string"):
                    continue
                c = spec.constraints
                for key, label in (("min", "Min"), ("max", "Max"), ("exclusiveMin", "ExclusiveMin"),
                                   ("exclusiveMax", "ExclusiveMax")):
                    if key in c and spec.kind != "string":
                        rows.append(f"        public const {self.ctype(spec)} {pascal(f.name)}{label} = {self.literal(spec, c[key])};")
                if "maxLength" in c:
                    rows.append(f"        public const int {pascal(f.name)}MaxLength = {c['maxLength']};")
            if rows:
                self.w(f"    /// <summary>Bornes des champs de {name}.</summary>")
                self.w(f"    public static class {name}Limits")
                self.w("    {")
                self.lines += rows
                self.w("    }")
                self.w()

    def defaults_helpers(self) -> None:
        jagged: dict[str, Spec] = {}
        filled: dict[str, Spec] = {}
        for st in self.m.structs.values():
            for f in st.fields:
                if f.default == "$itemDefaults":
                    if f.spec.item.kind == "array":
                        jagged[self._jagged_name(f.spec)] = f.spec
                    else:
                        filled[f.spec.item.ref] = f.spec
        self.w("    internal static class Defaults")
        self.w("    {")
        for name, spec in jagged.items():
            t = spec.item.item.ref
            rows, cols = spec.array["length"], spec.item.array["length"]
            self.w(f"        internal static {t}[][] Jagged{name}()")
            self.w("        {")
            self.w(f"            {t}[][] result = new {t}[{rows}][];")
            self.w(f"            for (int i = 0; i < {rows}; ++i)")
            self.w("            {")
            self.w(f"                result[i] = new {t}[{cols}];")
            self.w(f"                for (int j = 0; j < {cols}; ++j)")
            self.w("                {")
            self.w(f"                    result[i][j] = new {t}();")
            self.w("                }")
            self.w("            }")
            self.w("            return result;")
            self.w("        }")
        for t in filled:
            self.w(f"        internal static {t}[] Filled{t}(int count)")
            self.w("        {")
            self.w(f"            {t}[] result = new {t}[count];")
            self.w("            for (int i = 0; i < count; ++i)")
            self.w("            {")
            self.w(f"                result[i] = new {t}();")
            self.w("            }")
            self.w("            return result;")
            self.w("        }")
        self.w("    }")
        self.w()

    def union(self, name: str) -> None:
        u = self.m.unions[name]
        disc_enum = self.m.structs[u.members[0]].field(u.discriminator).spec.ref
        base = self.bases.get(name)
        self.doc(f"{u.doc} Discriminant JSON « {u.discriminator} ».", "    ")
        self.w(f"    public abstract class {name}{(' : ' + base) if base else ''}")
        self.w("    {")
        self.w(f"        internal {name}()")
        self.w("        {")
        self.w("        }")
        self.w()
        self.w(f"        public abstract {disc_enum} {pascal(u.discriminator)} {{ get; }}")
        self.w("    }")
        self.w()

    def switch_base(self, f) -> None:
        self.doc(f"Charge utile choisie par « {f.spec.switch_field} ».", "    ")
        self.w(f"    public abstract class {f.spec.switch_base}")
        self.w("    {")
        self.w(f"        internal {f.spec.switch_base}()")
        self.w("        {")
        self.w("        }")
        self.w("    }")
        self.w()

    def struct(self, name: str) -> None:
        st = self.m.structs[name]
        base = self.bases.get(name)
        union_disc = None
        if base in self.m.unions:
            union_disc = self.m.unions[base].discriminator
        self.doc(f"{st.doc} [{st.contract}]", "    ")
        self.w(f"    public sealed class {name}{(' : ' + base) if base else ''}")
        self.w("    {")
        self.w(f"        public {name}()")
        self.w("        {")
        for f in st.fields:
            if f.name == union_disc:
                continue
            p = pascal(f.name)
            c = f.spec.constraints
            if f.spec.kind == "switch":
                first = self.m.enums[st.field(f.spec.switch_field).spec.ref].values[0].wire
                self.w(f"            this.{p} = new {f.spec.cases[first].ref}();")
            elif f.nullable or (not f.required and not f.has_default):
                continue
            elif "const" in c:
                self.w(f"            this.{p} = {self.literal(f.spec, c['const'])};")
            elif f.has_default:
                self.w(f"            this.{p} = {self.default_expr(f.spec, f.default)};")
            elif f.spec.kind == "struct":
                self.w(f"            this.{p} = new {f.spec.ref}();")
            elif f.spec.kind == "array":
                if "length" in f.spec.array:
                    self.w(f"            this.{p} = new {self.ctype(f.spec.item)}[{f.spec.array['length']}];")
                else:
                    self.w(f"            this.{p} = new {self.ctype(f.spec)}();")
        self.w("        }")
        for f in st.fields:
            p = pascal(f.name)
            if p == name or f.name in CS_KEYWORDS:
                raise ValueError(f"{name}.{f.name} : nom de propriété C# invalide")
            if camel_roundtrip(f.name) != f.name:
                raise ValueError(f"{name}.{f.name} : JsonNamingPolicy.CamelCase ne restitue pas le nom JSON")
            self.w()
            doc = f.doc or ""
            self.doc(f"JSON « {f.name} ». {doc}".strip(), "        ")
            if f.name == union_disc:
                lit = self.literal(f.spec, f.spec.constraints["const"])
                self.w(f"        public override {self.ctype(f.spec)} {p}")
                self.w("        {")
                self.w(f"            get {{ return {lit}; }}")
                self.w("        }")
                continue
            t = self.ctype(f.spec)
            if (f.nullable or (not f.required and not f.has_default)) and f.spec.kind in CS_VALUE_TYPES | {"enum"}:
                t += "?"
            self.w(f"        public {t} {p} {{ get; set; }}")
        self.w("    }")
        self.w()


def generate_csharp(m: Manifest) -> str:
    return CsGen(m).gen()
