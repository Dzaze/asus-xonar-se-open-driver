"""Génération de l'en-tête C++20 des contrats et du test de conformité DSP.

En-tête autonome (bibliothèque standard seulement) : versions, GUID, clés de
propriété, constantes, énumérations et tables de noms filaires, bornes des
champs, DTO avec défauts C++. Aucun codec JSON : le choix du parseur appartient
à E2-01. Sortie déterministe : ordre du manifeste, fins de ligne LF.
"""

from __future__ import annotations

from typing import Any

from .model import Field, Manifest, Spec

CPP_INT = {"u8": "std::uint8_t", "u16": "std::uint16_t", "u32": "std::uint32_t",
           "u64": "std::uint64_t", "i32": "std::int32_t"}
HEADER = """// <auto-generated>
// Généré par contracts/generate.py depuis contracts/manifest.json.
// Empreinte du manifeste (sha256, fins de ligne LF) : {sha}
// NE PAS MODIFIER À LA MAIN. Toute évolution passe par le manifeste ; un
// changement de version majeure exige un ADR, une migration et des tests.
// </auto-generated>
"""


def cpp_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            raise ValueError(f"caractère non ASCII dans une constante : {s!r}")
    return '"' + "".join(out) + '"'


def cpp_double(v: Any) -> str:
    r = repr(float(v))
    return r if ("." in r or "e" in r or "inf" in r) else r + ".0"


def cpp_int(kind: str, v: int) -> str:
    if kind == "u64":
        return f"{v}ull"
    if kind in ("u8", "u16", "u32"):
        return f"{v}u"
    return str(v)


def guid_parts(value: str) -> str:
    h = value.replace("-", "")
    d1, d2, d3 = h[0:8], h[8:12], h[12:16]
    d4 = ", ".join(f"0x{h[i:i + 2]}" for i in range(16, 32, 2))
    return f"0x{d1}u, 0x{d2}u, 0x{d3}u, {{{{{d4}}}}}"


def comment(text: str, indent: str = "") -> list[str]:
    return [f"{indent}// {line}" for line in text.splitlines()] if text else []


class CppGen:
    def __init__(self, m: Manifest):
        self.m = m
        self.lines: list[str] = []

    def w(self, line: str = "") -> None:
        self.lines.append(line)

    # ---------------------------------------------------------------- types
    def ctype(self, spec: Spec) -> str:
        k = spec.kind
        if k == "bool":
            return "bool"
        if k == "f64":
            return "double"
        if k in CPP_INT:
            return CPP_INT[k]
        if k == "string":
            return "std::string"
        if k == "json":
            return "RawJson"
        if k in ("enum", "struct", "union"):
            return spec.ref
        if k == "switch":
            return spec.switch_base
        if k == "array":
            n = spec.array.get("length")
            inner = self.ctype(spec.item)
            return f"std::array<{inner}, {n}>" if n is not None else f"std::vector<{inner}>"
        raise ValueError(k)

    def literal(self, spec: Spec, v: Any) -> str:
        k = spec.kind
        if k == "bool":
            return "true" if v else "false"
        if k == "f64":
            return cpp_double(v)
        if k in CPP_INT:
            return cpp_int(k, v)
        if k == "enum":
            return f"{spec.ref}::{self.m.enums[spec.ref].by_wire(v).id}"
        if k == "string":
            return cpp_str(v)
        if k == "array":
            return "{{" + ", ".join(self.literal(spec.item, x) for x in v) + "}}"
        raise ValueError(k)

    def field_decl(self, f: Field) -> str:
        t = self.ctype(f.spec)
        optional = f.nullable or (not f.required and not f.has_default)
        if optional:
            return f"std::optional<{t}> {f.name}{{}};"
        c = f.spec.constraints
        if "const" in c:
            return f"{t} {f.name} = {self.literal(f.spec, c['const'])};"
        if f.has_default:
            if isinstance(f.default, dict) or f.default == "$itemDefaults":
                return f"{t} {f.name}{{}};"
            if f.spec.kind == "array":
                return f"{t} {f.name}{self.literal(f.spec, f.default)};"
            return f"{t} {f.name} = {self.literal(f.spec, f.default)};"
        return f"{t} {f.name}{{}};"

    # --------------------------------------------------------------- sections
    def gen(self) -> str:
        m = self.m
        self.lines = HEADER.format(sha=m.sha256).splitlines()
        self.w("#pragma once")
        self.w()
        for inc in ("array", "cstddef", "cstdint", "optional", "string", "string_view", "variant", "vector"):
            self.w(f"#include <{inc}>")
        self.w()
        self.w("namespace xonar::contracts::v1 {")
        self.w()
        self.w(f'inline constexpr std::string_view kManifestSha256 = "{m.sha256}";')
        self.w()
        self.section("Versions des contrats C1…C8 (§1 du backlog)")
        self.w("struct ContractVersion {")
        self.w("    std::string_view id;")
        self.w("    std::uint16_t major;")
        self.w("    std::uint16_t minor;")
        self.w("};")
        items = ", ".join(f'ContractVersion{{"{c["id"]}", {c["major"]}u, {c["minor"]}u}}' for c in m.contracts)
        self.w(f"inline constexpr std::array<ContractVersion, {len(m.contracts)}> kContractVersions{{{{{items}}}}};")
        for c in m.contracts:
            self.w(f"inline constexpr std::uint16_t k{c['id']}Major = {c['major']}u; // {c['title']}")
            self.w(f"inline constexpr std::uint16_t k{c['id']}Minor = {c['minor']}u;")
        self.w()
        self.section("GUID attribués une seule fois par E0-02")
        self.w("struct Guid {")
        self.w("    std::uint32_t data1;")
        self.w("    std::uint16_t data2;")
        self.w("    std::uint16_t data3;")
        self.w("    std::array<std::uint8_t, 8> data4;")
        self.w("    friend constexpr bool operator==(const Guid&, const Guid&) = default;")
        self.w("};")
        self.w()
        for g in m.guids.values():
            self.lines += comment(f"{g['doc']} [{g['contract']}]")
            self.w(f"inline constexpr Guid k{g['id']}{{{guid_parts(g['value'])}}};")
            self.w(f'inline constexpr std::string_view k{g["id"]}String = "{{{g["value"]}}}";')
        self.w()
        self.w("struct PropertyKey {")
        self.w("    Guid fmtid;")
        self.w("    std::uint32_t pid;")
        self.w("    friend constexpr bool operator==(const PropertyKey&, const PropertyKey&) = default;")
        self.w("};")
        for pk in m.property_keys:
            self.lines += comment(f"{pk['doc']} [{pk['contract']}]")
            self.w(f"inline constexpr PropertyKey k{pk['id']}{{k{pk['fmtid']}, {pk['pid']}u}};")
        self.w()
        self.w("// Objet JSON brut (texte UTF-8) transmis sans validation d'enveloppe ; son")
        self.w("// analyse relève du codec choisi par E2-01.")
        self.w("struct RawJson {")
        self.w("    std::string text;")
        self.w("};")
        self.w()
        self.section("Énumérations et noms filaires")
        for e in m.enums.values():
            if e.emit:
                self.enum(e)
        self.section("Constantes")
        for c in m.constants.values():
            self.constant(c)
        self.w()
        self.section("Bornes des champs (pour l'interface et les validateurs)")
        self.w("namespace limits {")
        for name in m.type_order():
            if name in m.structs:
                self.limits(name)
        self.w("} // namespace limits")
        self.w()
        self.section("DTO (forme normalisée ; défauts identiques à xonar::dsp::Profile)")
        for name in m.type_order():
            if name in m.unions:
                u = m.unions[name]
                self.lines += comment(f"{u.doc} Discriminant : « {u.discriminator} ».")
                self.w(f"using {name} = std::variant<{', '.join(u.members)}>;")
                self.w()
            else:
                self.struct(name)
        self.w("} // namespace xonar::contracts::v1")
        return "\n".join(self.lines) + "\n"

    def section(self, title: str) -> None:
        self.w(f"// {'-' * 74}")
        self.w(f"// {title}")
        self.w(f"// {'-' * 74}")
        self.w()

    def enum(self, e) -> None:
        n = len(e.values)
        self.lines += comment(f"{e.doc} [{e.contract}]")
        self.w(f"enum class {e.id} : std::uint8_t {{")
        for v in e.values:
            self.w(f"    {v.id} = {v.index},{(' // ' + v.doc) if v.doc else ''}")
        self.w("};")
        self.w(f"inline constexpr std::size_t k{e.id}Count = {n};")
        vals = ", ".join(f"{e.id}::{v.id}" for v in e.values)
        self.w(f"inline constexpr std::array<{e.id}, {n}> kAll{e.id}{{{{{vals}}}}};")
        self.w()
        self.w(f"[[nodiscard]] constexpr std::string_view toWire({e.id} value) noexcept {{")
        self.w("    switch (value) {")
        for v in e.values:
            self.w(f'    case {e.id}::{v.id}: return "{v.wire}";')
        self.w("    }")
        self.w("    return {};")
        self.w("}")
        self.w()
        self.w(f"[[nodiscard]] constexpr bool fromWire(std::string_view text, {e.id}& out) noexcept {{")
        for v in e.values:
            self.w(f'    if (text == "{v.wire}") {{ out = {e.id}::{v.id}; return true; }}')
        self.w("    return false;")
        self.w("}")
        self.w()
        for an, at in e.attrs.items():
            if at.startswith("enum:"):
                rt = at[5:]
                if list(self.m.enums).index(rt) > list(self.m.enums).index(e.id):
                    raise ValueError(f"{e.id}.{an} : {rt} doit précéder {e.id} dans le manifeste")
                spec = Spec("enum", ref=rt)
                fallback = f"{rt}{{}}"
            else:
                spec = Spec(at)
                fallback = "{}"
            self.w(f"[[nodiscard]] constexpr {self.ctype(spec)} {an}Of({e.id} value) noexcept {{")
            self.w("    switch (value) {")
            for v in e.values:
                self.w(f"    case {e.id}::{v.id}: return {self.literal(spec, v.attrs[an])};")
            self.w("    }")
            self.w(f"    return {fallback};")
            self.w("}")
            self.w()

    def constant(self, c) -> None:
        self.lines += comment(f"{c.doc} [{c.contract}]")
        t = c.type
        if isinstance(t, dict):
            item = t["array"]
            spec = Spec("enum", ref=item[5:]) if item.startswith("enum:") else Spec(item)
            vals = ", ".join(self.literal(spec, v) for v in c.value)
            self.w(f"inline constexpr std::array<{self.ctype(spec)}, {len(c.value)}> k{c.id}{{{{{vals}}}}};")
        elif t == "string":
            self.w(f"inline constexpr std::string_view k{c.id} = {cpp_str(c.value)};")
            self.w(f"inline constexpr std::wstring_view k{c.id}W = L{cpp_str(c.value)};")
        else:
            spec = Spec(t)
            self.w(f"inline constexpr {self.ctype(spec)} k{c.id} = {self.literal(spec, c.value)};")

    def limits(self, name: str) -> None:
        st = self.m.structs[name]
        rows: list[str] = []
        for f in st.fields:
            spec = f.spec
            if spec.kind == "array":
                if "length" in spec.array:
                    rows.append(f"    static constexpr std::size_t {f.name}Length = {spec.array['length']};")
                if "maxItems" in spec.array:
                    rows.append(f"    static constexpr std::size_t {f.name}MaxItems = {spec.array['maxItems']};")
                while spec.kind == "array":
                    spec = spec.item
            if spec.kind not in ("f64", *CPP_INT, "string"):
                continue
            c = spec.constraints
            ct = "double" if spec.kind == "f64" else CPP_INT.get(spec.kind, "std::size_t")
            for key, label in (("min", "Min"), ("max", "Max"), ("exclusiveMin", "ExclusiveMin"),
                               ("exclusiveMax", "ExclusiveMax")):
                if key in c:
                    rows.append(f"    static constexpr {ct} {f.name}{label} = {self.literal(spec, c[key])};")
            if "maxLength" in c:
                rows.append(f"    static constexpr std::size_t {f.name}MaxLength = {c['maxLength']};")
        if rows:
            self.w(f"struct {name} {{")
            self.lines += rows
            self.w("};")

    def struct(self, name: str) -> None:
        st = self.m.structs[name]
        for f in st.fields:
            if f.spec.kind == "switch":
                alts: list[str] = []
                for case in f.spec.cases.values():
                    t = self.ctype(case)
                    if t not in alts:
                        alts.append(t)
                self.lines += comment(f"Charge utile choisie par « {f.spec.switch_field} ».")
                self.w(f"using {f.spec.switch_base} = std::variant<{', '.join(alts)}>;")
                self.w()
        self.lines += comment(f"{st.doc} [{st.contract}]")
        self.w(f"struct {name} {{")
        for f in st.fields:
            if f.doc:
                self.lines += comment(f.doc, "    ")
            self.w(f"    {self.field_decl(f)}")
        self.w("};")
        self.w()


def generate_header(m: Manifest) -> str:
    return CppGen(m).gen()


# ----------------------------------------------------------------------------
# Test de conformité : défauts et énumérations du manifeste == dsp-core.
# ----------------------------------------------------------------------------
def generate_dsp_conformance(m: Manifest) -> str:
    lines = HEADER.format(sha=m.sha256).splitlines()
    lines += [
        "// Inclus par tests/contracts/cpp/conformance_main.cpp, qui définit",
        "// XONAR_CHECK(condition, libellé) et les espaces de noms dsp et c.",
        "",
        "// Énumérations miroirs",
    ]
    for e in m.enums.values():
        mir = e.mirror
        if not mir:
            continue
        for v in e.values:
            lines.append(f"static_assert(static_cast<int>({mir['type']}::{v.id}) == static_cast<int>(c::{e.id}::{v.id}),"
                         f' "{e.id}::{v.id}");')
        if "count" in mir:
            lines.append(f"static_assert(static_cast<std::size_t>({mir['count']}) == c::k{e.id}Count, \"{e.id} : cardinal\");")
        for an, fn in mir.get("attrs", {}).items():
            for v in e.values:
                lines.append(f"static_assert({fn}({mir['type']}::{v.id}) == c::{an}Of(c::{e.id}::{v.id}), \"{e.id}::{v.id}.{an}\");")
    lines += ["", "// Constantes miroirs"]
    for c in m.constants.values():
        if c.mirror:
            lines.append(f"static_assert(static_cast<std::uint64_t>({c.mirror}) == static_cast<std::uint64_t>(c::k{c.id}), \"{c.id}\");")
    lines += ["", "inline void checkDspDefaults() {",
              "    const dsp::Profile ref{};",
              "    const c::ProfileDocument dto{};"]
    gen = _Conf(m, lines)
    gen.walk("ProfileDocument", "dto", "ref", None)
    lines.append("}")
    return "\n".join(lines) + "\n"


class _Conf:
    def __init__(self, m: Manifest, lines: list[str]):
        self.m = m
        self.lines = lines
        self.loop = 0

    def emit_scalar(self, spec: Spec, dto: str, dsp: str, indent: str) -> None:
        label = dto.replace('"', "")
        if spec.kind == "f64":
            self.lines.append(f'{indent}XONAR_CHECK(static_cast<float>({dto}) == {dsp}, "{label}");')
        else:
            self.lines.append(f'{indent}XONAR_CHECK({dto} == {dsp}, "{label}");')

    def walk(self, sid: str, dto: str, dsp_base: str, dsp_prefix: str | None, indent: str = "    ") -> None:
        st = self.m.structs[sid]
        for f in st.fields:
            if f.spec.kind == "struct":
                self.walk(f.spec.ref, f"{dto}.{f.name}", dsp_base, dsp_prefix, indent)
                continue
            if not f.dsp:
                continue
            dsp = f"{dsp_base}.{f.dsp}" if dsp_prefix is None else f"{dsp_prefix}.{f.dsp}"
            spec, d_expr, s_expr, depth = f.spec, f"{dto}.{f.name}", dsp, 0
            ind = indent
            while spec.kind == "array":
                var = f"i{self.loop}"
                self.loop += 1
                self.lines.append(f"{ind}static_assert(std::tuple_size_v<std::remove_cvref_t<decltype({s_expr})>> == "
                                  f"std::tuple_size_v<std::remove_cvref_t<decltype({d_expr})>>);")
                self.lines.append(f"{ind}for (std::size_t {var} = 0; {var} < {d_expr}.size(); ++{var}) {{")
                d_expr, s_expr = f"{d_expr}[{var}]", f"{s_expr}[{var}]"
                spec = spec.item
                ind += "    "
                depth += 1
            if spec.kind == "struct":
                self.walk(spec.ref, d_expr, dsp_base, s_expr, ind)
            else:
                self.emit_scalar(spec, d_expr, s_expr, ind)
            for _ in range(depth):
                ind = ind[:-4]
                self.lines.append(f"{ind}}}")
